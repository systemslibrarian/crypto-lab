#!/usr/bin/env node
/*
 * depth-audit-report.js — the report writer for tools/depth-audit.js.
 *
 * Not runnable on its own; `node tools/depth-audit.js` calls main() here.
 *
 * Kept separate because the two jobs fail differently. The classifier decides
 * what the evidence says about one lab; this file decides how the fleet is
 * ordered and what the prose claims. A change to a ranking rule should not be
 * able to alter a dimension verdict by accident.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { classify, walk, labs, shas, WEIGHTS } = require('./depth-audit.js');

const ROOT = path.join(__dirname, '..');
const SCRATCH = path.join(ROOT, '.scratch');
const OWNER = 'systemslibrarian';
/* Local date, not UTC. The first run wrote a file dated a day ahead of the
   maintainer's own clock, which is a small thing that makes a dated audit
   confusing to line up against the runs it cites. */
const TODAY = (() => {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
})();
const OUT = () => path.join(ROOT, 'audits', `DEPTH-AUDIT-${TODAY}.md`);
const BEGIN = '<!-- depth-audit:begin — generated by tools/depth-audit.js; do not edit by hand -->';
const END = '<!-- depth-audit:end -->';

/* Which labs a course module teaches. Read from the teach sources rather than
   assumed, because teaching impact is the first ranking key and a guess there
   reorders the whole list. */
function courseLabs() {
  const dir = path.join(ROOT, 'teach', '_src');
  const found = new Set();
  if (!fs.existsSync(dir)) return found;
  for (const f of walk(dir)) {
    const text = fs.readFileSync(path.join(dir, f), 'utf8');
    for (const m of text.matchAll(/crypto-lab-[a-z0-9-]+/g)) found.add(m[0]);
  }
  return found;
}

/* Whether a published vector plausibly EXISTS for what a lab implements - the
   effort half of the ranking. Taken from the catalog's own standards field, so
   "a published vector could close this" is derived from the algorithm rather
   than guessed from the lab's name. */
function standardsByLab() {
  const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  const map = new Map();
  /* Split on the card element and read each block whole. The first version
     matched href-then-up-to-1200-characters, and cards now carry the catalog's
     evidence attributes plus a hand-written overlap sentence, so almost every
     card is longer than that window: the lookup matched 2 of 209. Everything
     downstream ran on an empty map - the ranking table came out with one row,
     209 carded labs were published as "no card in index.html", and ninety labs
     were filed "correctly light, no standards body" on the strength of nothing. */
  const re = /<a class="(?:project|feature)-card[^"]*"[\s\S]*?<\/a>/g;
  let m;
  while ((m = re.exec(html)) !== null) {
    const block = m[0];
    const href = /href="https:\/\/systemslibrarian\.github\.io\/([^/"]+)\//.exec(block);
    if (!href) continue;
    const std = /\sdata-standards="([^"]*)"/.exec(block);
    const impl = /\sdata-implements="([^"]*)"/.exec(block);
    map.set(href[1], {
      bodies: std ? std[1].split(' | ').filter(Boolean) : [],
      implements: impl && impl[1] !== 'UNKNOWN' && impl[1] !== 'NOT-SCANNED'
        ? impl[1].split(' | ').map((x) => x.split('@')[0]) : [],
    });
  }
  if (map.size < 100) {
    throw new Error(`card lookup matched only ${map.size} cards in index.html; the ranking would be derived from an empty map`);
  }
  return map;
}

/* README claiming more assurance than the files show. */
const ASSURANCE_CLAIM = [
  /\ball\s+(?:the\s+)?(?:NIST|official|published)?\s*(?:test\s+)?vectors\b/i,
  /\bknown[- ]answer tests?\b/i,
  /\bKAT\b/,
  /\bchecked against\b.*\bvectors?\b/i,
  /\bvalidated against\b/i,
  /\bconformance (?:tested|suite)\b/i,
];

function link(lab, sha, anchor) {
  if (!anchor) return '—';
  const [file, line] = anchor.split(':');
  const frag = line ? `#L${line}` : '';
  return `[${anchor}](https://github.com/${OWNER}/${lab}/blob/${sha}/${file}${frag})`;
}

function build(rows, meta) {
  const L = [];
  const course = meta.course;
  const std = meta.standards;
  const sha = meta.shas;
  const at = (lab) => (sha.get(lab) ? sha.get(lab).sha : 'main');

  /* The reference rule is the 2026-09-25 audit's, recovered from its own list
     rather than invented: every one of its reference labs scores its full
     assessed weight, webauthn at 7/7 with ground truth and independent check
     UNRESOLVED. So a reference lab is one where nothing assessed came back
     not-met - which is a different and better rule than "both heavy dimensions
     credited", because it admits a lab whose strength is its negative tests. */
  /* Every dimension adjudicated AND every one credited. The 2026-09-25 audit's
     own rule was "nothing assessed came back not-met", which its hand-picked
     subset made meaningful; applied mechanically to the whole fleet it admits a
     lab with most dimensions unresolved and nothing to fail, and the list stops
     meaning anything. Requiring the full assessed weight keeps the property that
     matters - nothing unresolved, nothing missing - and is a bar a reader can
     check against the ledger. */
  const heavyBoth = (r) => r.assessed === 15 && r.earned === 15;
  const declaresModel = (r) => r.dims.H === '+';
  const frac = (r) => (r.assessed ? r.earned / r.assessed : 0);

  /* Reference: both heavy dimensions credited. Not "highest score" - a light gate
     with real external truth is the thing others should be brought up to, and
     that is exactly what the weights say. */
  const reference = rows.filter(heavyBoth).sort((a, b) => frac(b) - frac(a) || a.lab.localeCompare(b.lab));

  /* Correctly light: the lab says what it is, and what it is does not need an
     outside vector. Derived as: limits stated, no published standards body behind
     what it implements, and ground truth not credited. A toy SPN has no ACVP. */
  const light = rows.filter((r) => !heavyBoth(r) && declaresModel(r)
    && (std.get(r.lab) ? std.get(r.lab).bodies.length === 0 : true) && r.dims.T !== '+')
    .sort((a, b) => a.lab.localeCompare(b.lab));
  const lightSet = new Set(light.map((r) => r.lab));

  /* Needs work: everything else, teaching impact first, then closure effort.
     Effort is derived: a lab whose implemented algorithms answer to a standards
     body can close T with a published vector; one without needs new work. */
  /* A repository with no card is not an exhibit and is not ranked.
     crypto-lab-blind-oracle-api is a headless service with no page and no card,
     and CLAUDE.md records it as a fair skip; ranking it as a lab needing tests
     would be the audit inventing a deliverable nobody owes. */
  const uncarded = rows.filter((r) => !meta.standards.has(r.lab));
  const uncardedSet = new Set(uncarded.map((r) => r.lab));
  const needs = rows.filter((r) => !heavyBoth(r) && !lightSet.has(r.lab) && !uncardedSet.has(r.lab));
  const closable = (r) => (std.get(r.lab) && std.get(r.lab).bodies.length > 0 ? 1 : 0);
  needs.sort((a, b) => (course.has(b.lab) ? 1 : 0) - (course.has(a.lab) ? 1 : 0)
    || closable(b) - closable(a)
    || frac(a) - frac(b)
    || a.lab.localeCompare(b.lab));

  L.push(`# Depth audit — ${TODAY}`);
  L.push('');
  L.push(BEGIN);
  L.push('');
  L.push('## What this is, and what it is not');
  L.push('');
  L.push('A **generated** pass over every lab-shaped repository in the organisation, derived from');
  L.push('an export of each remote default branch. It extends rather than replaces the hand-read');
  L.push('[2026-09-25 audit](DEPTH-AUDIT-2026-09-25.md) and [its follow-up](DEPTH-AUDIT-FOLLOWUP-2026-09-26.md),');
  L.push('which stated their own limit plainly: source-scan coverage is not dimension coverage, most');
  L.push('labs carried `?` on the dimensions that weigh most, and neither would rank from partial');
  L.push('scores. This file exists to make those dimensions derivable, and re-derivable — the reports');
  L.push('above are snapshots of a fleet that moves, and `node tools/depth-audit.js check` fails when');
  L.push('this one drifts from the exports it was built from.');
  L.push('');
  L.push('It is a record of **what is tested and by what**. It is not a security assessment, and no');
  L.push('row here should be read as saying a lab is secure, correct, or verified.');
  L.push('');
  L.push('**A lexical hit is a lead, not proof.** That rule is inherited from the 2026-09-25 audit and');
  L.push('governs ground truth: a file naming a standard with no fixed material beside it is recorded');
  L.push('as unresolved, not as credited.');
  L.push('');
  L.push('## Coverage');
  L.push('');
  L.push('| Scope | Labs | Meaning |');
  L.push('|---|---:|---|');
  L.push(`| Remote default branches exported and read | ${rows.length} | Every lab-shaped repository the organisation lists |`);
  L.push(`| Export failures | ${meta.failed} | A repository that could not be read would appear here, not as a low score |`);
  L.push(`| Carrying source in a language this tool does not read | ${rows.filter((r) => r.unread.length).length} | Reported per lab; those dimensions stay unresolved rather than scoring zero |`);
  L.push(`| Carrying vendored paths, omitted from the read | ${rows.filter((r) => r.vendoredPaths).length} | First-party findings are a floor for these |`);
  L.push(`| In a course module | ${rows.filter((r) => course.has(r.lab)).length} | Derived from \`teach/_src\`; first ranking key |`);
  L.push('');
  const unresolved = {};
  for (const k of Object.keys(WEIGHTS)) unresolved[k] = rows.filter((r) => r.dims[k] === '?').length;
  L.push('| Dimension | Weight | Credited when | Unresolved |');
  L.push('|---|---:|---|---:|');
  L.push(`| T ground truth | ${WEIGHTS.T} | a named published source cited beside fixed material | ${unresolved.T} |`);
  L.push(`| I independent check | ${WEIGHTS.I} | a test reads an outside implementation, or a separate verification script runs | ${unresolved.I} |`);
  L.push(`| C displayed claim | ${WEIGHTS.C} | a claims spec asserts what the page shows | ${unresolved.C} |`);
  L.push(`| N negative test | ${WEIGHTS.N} | a throw, rejection, or a case named for the failure it forces | ${unresolved.N} |`);
  L.push(`| G deploy gate | ${WEIGHTS.G} | the publishing workflow runs a test step; engines are named, never inferred | ${unresolved.G} |`);
  L.push(`| H limits and guidance | ${WEIGHTS.H} | README states scale or limits | ${unresolved.H} |`);
  L.push('');
  L.push('`+` credited · `0` inspected and not met · `?` not derivable here. **A `?` is excluded from');
  L.push('both the earned and the assessed weight**, so an unknown is never averaged into a score.');
  L.push('Two scores with different assessed weights are not comparable as fractions.');
  L.push('');
  L.push('**The seventh dimension is not scored here.** Whether a test step runs and reports zero');
  L.push('tests is credited in this rubric only on observed run output, which is file-invisible.');
  L.push('That evidence is gathered against pinned commits in');
  L.push('[the observed-test-runs supplement](https://github.com/systemslibrarian/crypto-lab/pull/29).');
  L.push('What this tool can see is the structural hazard that makes a zero-test run possible, and it');
  L.push('reports that separately below rather than scoring a weaker answer to the same question.');
  L.push('');

  /* ---- reference ---- */
  L.push('## Reference labs');
  L.push('');
  L.push('Both heavy dimensions credited: an outside truth to check against, and something other than');
  L.push('the implementation doing the checking. This is the bar others would be brought up to.');
  L.push('');
  L.push('| Lab | Score | What it does that others here do not | Ground truth | Independent check |');
  L.push('|---|---:|---|---|---|');
  for (const r of reference) {
    L.push(`| [${r.lab.replace('crypto-lab-', '')}](https://github.com/${OWNER}/${r.lab}/tree/${at(r.lab)}) | ${r.earned}/${r.assessed} | ${r.note.T}; ${r.note.I} | ${link(r.lab, at(r.lab), r.evidence.T)} | ${link(r.lab, at(r.lab), r.evidence.I)} |`);
  }
  L.push('');

  /* ---- calibration against the hand-read audit ---- */
  L.push('## Calibration against the hand-read audit');
  L.push('');
  L.push('The labs the [2026-09-25 audit](DEPTH-AUDIT-2026-09-25.md) named as references, scored again');
  L.push('by this tool. Disagreement is recorded rather than tuned away: where a careful reader and a');
  L.push('derivation differ, the difference is usually definitional and worth seeing.');
  L.push('');
  L.push('| Lab | This tool | Reference by this rule | Where the two differ |');
  L.push('|---|---:|---|---|');
  for (const short of meta.priorReferences) {
    const r = rows.find((x) => x.lab === `crypto-lab-${short}`);
    if (!r) { L.push(`| ${short} | — | not exported | the repository was not read |`); continue; }
    const isRef = heavyBoth(r);
    const notMet = Object.keys(WEIGHTS).filter((k) => r.dims[k] === '0');
    L.push(`| ${short} | ${r.earned}/${r.assessed} | ${isRef ? 'yes' : 'no'} | ${notMet.length ? `this tool records ${notMet.join(', ')} as inspected and not met, where the hand read left them unresolved` : 'agrees'} |`);
  }
  L.push('');
  L.push('A dimension this tool marks `0` and a hand reader marked `?` is the commonest difference,');
  L.push('and it is a real one: `0` says the files were read and the thing is not there, `?` says the');
  L.push('question was not settled. The stricter mark is only better where the derivation is sound, so');
  L.push('the ledger below carries the anchor for every credited dimension and nothing else is claimed.');
  L.push('');

  /* ---- needs work ---- */
  L.push('## Needs work');
  L.push('');
  L.push('Ordered by teaching impact first — a lab a course module teaches ranks above one it does');
  L.push('not — then by closure effort, where a dimension a published vector could close ranks above');
  L.push('one needing new infrastructure. The highest-value addition names where the ground truth');
  L.push('would come from.');
  L.push('');
  L.push('| # | Lab | Course | Score | Missing | Highest-value addition | Where the truth comes from |');
  L.push('|---:|---|---|---:|---|---|---|');
  needs.forEach((r, i) => {
    const missing = Object.keys(WEIGHTS).filter((k) => r.dims[k] === '0');
    const s = std.get(r.lab);
    const bodies = s && s.bodies.length ? s.bodies.join(', ') : null;
    const algos = s && s.implements.length ? s.implements.slice(0, 3).join(', ') : null;
    let add;
    let from;
    if (r.dims.T === '0' || r.dims.T === '?') {
      add = 'Pin a published fixed vector for what it already computes, and keep the generated cases as the control.';
      from = bodies ? `${bodies} — ${algos || 'the algorithms on its card'}` : 'no standards body behind what it implements; ground truth would have to be a paper or a second implementation';
    } else if (r.dims.I === '0') {
      add = 'Check the same inputs against an outside implementation, or add a separate verification script.';
      from = algos ? `an outside library for ${algos}` : 'an outside library for the primitive it implements';
    } else if (r.dims.N === '0') {
      add = 'Add a case that forces a failure: tamper, wrong key, replay, or malformed input.';
      from = 'the lab\'s own reject path; no outside vector needed';
    } else if (r.dims.C === '0' || r.dims.C === '?') {
      add = 'Assert that a displayed value equals what the code computed, in a claims spec.';
      from = 'the computed value already under test';
    } else {
      add = 'Make the deploy wait for the tests it already has.';
      from = 'the workflow itself';
    }
    L.push(`| ${i + 1} | [${r.lab.replace('crypto-lab-', '')}](https://github.com/${OWNER}/${r.lab}/tree/${at(r.lab)}) | ${course.has(r.lab) ? 'yes' : 'no'} | ${r.earned}/${r.assessed} | ${missing.join(' ') || '—'} | ${add} | ${from} |`);
  });
  L.push('');

  /* ---- correctly light ---- */
  L.push('## Correctly light');
  L.push('');
  L.push('The depth matches what the exhibit claims. A toy construction built for a lesson has no');
  L.push('published vector to pin, and adding one would not make the lesson truer. Recorded so nobody');
  L.push('later reads a low ground-truth mark here as a defect to fix.');
  L.push('');
  L.push('| Lab | Score | Why the depth fits | Limits stated at |');
  L.push('|---|---:|---|---|');
  for (const r of light) {
    L.push(`| [${r.lab.replace('crypto-lab-', '')}](https://github.com/${OWNER}/${r.lab}/tree/${at(r.lab)}) | ${r.earned}/${r.assessed} | no standards body behind what it implements, and the README says what it is | ${link(r.lab, at(r.lab), r.evidence.H)} |`);
  }
  L.push('');

  L.push('## Outside the ranking: no card here');
  L.push('');
  L.push('Repositories the organisation lists that this catalog does not card. They are read and');
  L.push('scored like any other, and left out of the three groups because a ranking of exhibits should');
  L.push('not invent work for a repository that is not one.');
  L.push('');
  if (uncarded.length) {
    L.push('| Repository | Score | Why it is not ranked |');
    L.push('|---|---:|---|');
    for (const r of uncarded) {
      L.push(`| ${r.lab} | ${r.earned}/${r.assessed} | no card in \`index.html\`; ${r.unread.length ? `carries ${r.unread.join(', ')} this tool does not read` : 'not a carded exhibit'} |`);
    }
  } else L.push('_None._');
  L.push('');

  /* ---- copy that reads as advice ---- */
  L.push('## Copy that a wrong reader takes as advice');
  L.push('');
  L.push('Good teaching that could be read as deployment guidance for demo code, in the class of the');
  L.push('FROST finding already recorded in the follow-up. Listed as copy to qualify, not as defects.');
  L.push('');
  const withGuidance = rows.filter((r) => r.guidance.length);
  if (withGuidance.length) {
    L.push('| Lab | Where | Reads as |');
    L.push('|---|---|---|');
    for (const r of withGuidance) {
      for (const g of r.guidance) {
        L.push(`| ${r.lab.replace('crypto-lab-', '')} | ${link(r.lab, at(r.lab), `${g.file}:${g.line}`)} | ${g.why} |`);
      }
    }
  } else L.push('_None found by the patterns this tool reads._');
  L.push('');

  /* ---- stated assurance exceeding what was found ---- */
  L.push('## Stated assurance beyond what the files show');
  L.push('');
  L.push('A README describing known-answer or vector coverage where ground truth is not credited. This');
  L.push('is a claim to qualify or to close, not evidence that anything computes wrongly.');
  L.push('');
  const overstated = rows.filter((r) => r.overstated);
  if (overstated.length) {
    L.push('| Lab | README says | Ground truth |');
    L.push('|---|---|---|');
    for (const r of overstated) {
      L.push(`| ${r.lab.replace('crypto-lab-', '')} | ${link(r.lab, at(r.lab), r.overstated)} | ${r.dims.T} — ${r.note.T || 'not credited'} |`);
    }
  } else L.push('_None found._');
  L.push('');

  /* ---- zero-test hazard ---- */
  L.push('## Structural zero-test hazard');
  L.push('');
  L.push('A shape that lets a test step succeed while running nothing. Not an observation that any');
  L.push('run reported zero — that evidence is in the supplement linked above.');
  L.push('');
  const hazard = rows.filter((r) => r.zHazard.length);
  if (hazard.length) {
    L.push('| Lab | Hazard |');
    L.push('|---|---|');
    for (const r of hazard) L.push(`| ${r.lab.replace('crypto-lab-', '')} | ${r.zHazard.join('; ')} |`);
  } else L.push('_None found._');
  L.push('');

  /* ---- ledger ---- */
  L.push('## Per-lab ledger');
  L.push('');
  L.push('Every lab, with the commit read and an anchor for each credited dimension. `?` marks a');
  L.push('dimension this tool could not resolve; it is excluded from the score rather than counted');
  L.push('against the lab.');
  L.push('');
  L.push('| Lab | Commit read | T | I | C | N | G | H | Score | What the deploy waits for | Engines | Unread source |');
  L.push('|---|---|:-:|:-:|:-:|:-:|:-:|:-:|---:|---|---|---|');
  for (const r of [...rows].sort((a, b) => a.lab.localeCompare(b.lab))) {
    const s = at(r.lab);
    /* The gate's step list is printed, not just its verdict. A bare `+` reads the
       same for a lab gated on unit tests, browser claims, axe and a mutation
       sweep as for one gated on an accessibility scan alone, and the difference
       is the whole dimension. */
    const steps = r.gate.steps.length ? r.gate.steps.join(', ') : '—';
    const eng = r.gate.engines.length ? r.gate.engines.join(', ') : '—';
    const caveat = (r.gate.engineNote && r.gate.engineNote.length) ? ` (${r.gate.engineNote.join('; ')})` : '';
    L.push(`| [${r.lab.replace('crypto-lab-', '')}](https://github.com/${OWNER}/${r.lab}/tree/${s}) | \`${s.slice(0, 7)}\` | ${r.dims.T} | ${r.dims.I} | ${r.dims.C} | ${r.dims.N} | ${r.dims.G} | ${r.dims.H} | ${r.earned}/${r.assessed} | ${steps} | ${eng}${caveat} | ${r.unread.length ? r.unread.join(' ') : '—'} |`);
  }
  L.push('');
  L.push('## Evidence anchors');
  L.push('');
  L.push('| Lab | T | I | C | N | G | H |');
  L.push('|---|---|---|---|---|---|---|');
  for (const r of [...rows].sort((a, b) => a.lab.localeCompare(b.lab))) {
    const s = at(r.lab);
    L.push(`| ${r.lab.replace('crypto-lab-', '')} | ${link(r.lab, s, r.evidence.T)} | ${link(r.lab, s, r.evidence.I)} | ${link(r.lab, s, r.evidence.C)} | ${link(r.lab, s, r.evidence.N)} | ${link(r.lab, s, r.evidence.G)} | ${link(r.lab, s, r.evidence.H)} |`);
  }
  L.push('');
  L.push(END);
  return L.join('\n') + '\n';
}

function collect() {
  const all = labs();
  const sha = shas();
  const std = standardsByLab();
  const course = courseLabs();
  const rows = [];
  for (const lab of all) {
    const files = walk(path.join(SCRATCH, lab));
    const r = classify(lab, files);
    /* README claiming assurance the files do not show. */
    let overstated = null;
    const readme = (() => { try { return fs.readFileSync(path.join(SCRATCH, lab, 'README.md'), 'utf8'); } catch { return null; } })();
    if (readme && r.dims.T !== '+') {
      const lines = readme.split('\n');
      for (let i = 0; i < lines.length; i += 1) {
        if (ASSURANCE_CLAIM.some((re) => re.test(lines[i]))) { overstated = `README.md:${i + 1}`; break; }
      }
    }
    rows.push({ ...r, overstated });
  }
  const failedPath = path.join(SCRATCH, '.export-failed.tsv');
  const failed = fs.existsSync(failedPath)
    ? fs.readFileSync(failedPath, 'utf8').split('\n').filter(Boolean).length : 0;
  /* The prior audit's reference list, as a calibration set. */
  const priorReferences = ['kem-trap', 'drbg-arena', 'webauthn', 'frost-threshold',
    'protocol-checker', 'ec-point-arithmetic', 'attribute-gate'];
  return { rows, meta: { shas: sha, standards: std, course, failed, priorReferences } };
}

function doExport() {
  const script = path.join(__dirname, 'depth-audit-export.sh');
  execFileSync('bash', [script], { cwd: ROOT, stdio: 'inherit' });
}

function main() {
  const mode = process.argv[2];
  if (mode === 'export') return doExport();
  const { rows, meta } = collect();
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify(rows, null, 2));
    return;
  }
  const next = build(rows, meta);
  const out = OUT();
  if (mode === 'check') {
    if (!fs.existsSync(out)) {
      console.error(`ERROR no ${path.relative(ROOT, out)}. Run: node tools/depth-audit.js`);
      process.exit(1);
    }
    const cur = fs.readFileSync(out, 'utf8');
    const slice = (t) => t.slice(t.indexOf(BEGIN), t.indexOf(END) + END.length);
    if (slice(cur) === slice(next)) {
      console.log(`${path.relative(ROOT, out)} in step with the exports in .scratch/ (${rows.length} labs).`);
      return;
    }
    console.error(`OUT OF DATE ${path.relative(ROOT, out)}`);
    console.error('Run: node tools/depth-audit.js export && node tools/depth-audit.js');
    process.exit(1);
  }
  fs.writeFileSync(out, next);
  const cred = (k) => rows.filter((r) => r.dims[k] === '+').length;
  console.log(`${path.relative(ROOT, out)} written: ${rows.length} labs.`);
  console.log(`  credited — T ${cred('T')}  I ${cred('I')}  C ${cred('C')}  N ${cred('N')}  G ${cred('G')}  H ${cred('H')}`);
}

